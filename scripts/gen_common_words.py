"""Regenerate apps/core/src/esp_atlas_core/common_words_en.txt, the common-English list that keeps
a firmware's ordinary name words ("smart", "weather") from capturing queries (intent.py).

Offline and pinned: wordfreq is a generation-time tool only, never a runtime dependency of the API.

    pip install wordfreq==3.1.1
    python3 scripts/gen_common_words.py

The cutoff (Zipf >= 3.6, words of 4+ letters) is measured, not chosen by feel: on the 2026-11-15
catalog it bars every common word a firmware name contains while keeping every distinctive name
word that already routed (marauder 2.57, flipper 2.80, nemo 3.17, morse 3.52, saturn 3.54).
"""
import re
import sys
from pathlib import Path

WORDFREQ_VERSION = "3.1.1"
ZIPF_MIN = 3.6
OUT = Path(__file__).resolve().parents[1] / "apps/core/src/esp_atlas_core/common_words_en.txt"

HEADER = f"""\
# Common English words: 4+ letters, wordfreq zipf_frequency(word, "en") >= {ZIPF_MIN} (wordlist "best").
# Generated by scripts/gen_common_words.py with wordfreq {WORDFREQ_VERSION}; never edit by hand.
# Derived from wordfreq data by Robyn Speer, https://github.com/rspeer/wordfreq (see its NOTICE.md),
# licensed CC-BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/); this list is CC-BY-SA 4.0 too.
"""


def main():
    import wordfreq
    from importlib.metadata import version

    if version("wordfreq") != WORDFREQ_VERSION:
        sys.exit(f"wordfreq {WORDFREQ_VERSION} required, found {version('wordfreq')}")
    words = sorted({
        w for w in wordfreq.top_n_list("en", 200000, wordlist="best")
        if re.fullmatch(r"[a-z]{4,}", w) and wordfreq.zipf_frequency(w, "en") >= ZIPF_MIN
    })
    OUT.write_text(HEADER + "\n".join(words) + "\n", encoding="utf-8")
    print(f"{len(words)} words -> {OUT}")


if __name__ == "__main__":
    main()
